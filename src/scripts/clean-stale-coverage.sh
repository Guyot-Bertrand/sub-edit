#!/usr/bin/env bash
# Discards a coverage tree that a source move has made inconsistent.
#
# **The defect, and why nobody sees it coming.** `gcov` writes one `.gcno` per
# translation unit, next to its `.o`. A source file that changes location
# leaves one behind: the generator does not delete outputs it no longer
# produces, and the `.gcno` is not a declared output anyway — `ninja -t
# cleandead` removes the `.o` and leaves the `.gcno`. `gcovr` then hits a file
# whose source it can no longer find, and fails with a message that names
# neither the faulty file nor the remedy:
#
#     Could not open output file 'c++config.h##afd....gcov'
#         (gcovr could not infer a working directory that resolved it.)
#
# **Local only.** Continuous integration starts from a fresh tree and never
# meets an orphan. That is what makes the defect painful: it only hits whoever
# is working.
#
# **The criterion.** Only a source that DISAPPEARS orphans a `.gcno` — an
# addition orphans nothing. The list of compiled sources is therefore kept, and
# the whole tree is discarded as soon as one of them is gone. Discarding rather
# than pruning: the link between a `.gcno` and its source cannot be read from
# the file system without guessing the generator's layout, and guessing is what
# would delete the `.gcno` files of sources generated by `moc`.
#
# The price is a full rebuild, exactly when a rebuild is justified: a file
# move, which happens a few times a year. An addition costs nothing.

set -euo pipefail

readonly REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

readonly YELLOW=$'\033[33m'
readonly RESET=$'\033[0m'

build_dir="${REPO_ROOT}/build/coverage"

usage() {
    cat >&2 <<USAGE
usage: clean-stale-coverage.sh [--build-dir <directory>]

  --build-dir  coverage tree to check (default: build/coverage)
USAGE
    exit 2
}

while (( $# > 0 )); do
    case "$1" in
        --build-dir) [[ $# -ge 2 ]] || usage; build_dir="$2"; shift 2 ;;
        -h|--help)   usage ;;
        *)           printf 'unknown argument: %s\n' "$1" >&2; usage ;;
    esac
done

readonly MANIFEST="${build_dir}/.sources"

# The project's compilable sources, paths relative to the root, sorted.
# `sort` without a locale so that the order does not depend on the environment.
sources_now() {
    (cd "${REPO_ROOT}" && find src -name '*.cpp' -o -name '*.hpp' | LC_ALL=C sort)
}

# Nothing to compare: first pass, or tree already absent.
if [[ ! -f "${MANIFEST}" ]]; then
    mkdir -p "${build_dir}"
    sources_now > "${MANIFEST}"
    exit 0
fi

# A source of the previous record that is no longer there: the tree holds at
# least one `.gcno` that nothing attaches to a source any more.
gone=""
while IFS= read -r path; do
    [[ -n "${path}" ]] || continue
    if [[ ! -f "${REPO_ROOT}/${path}" ]]; then
        gone="${path}"
        break
    fi
done < "${MANIFEST}"

if [[ -n "${gone}" ]]; then
    printf '%scoverage tree discarded: %s has disappeared since the last measurement%s\n' \
        "${YELLOW}" "${gone}" "${RESET}"
    printf '  an orphaned .gcno would make gcovr fail without naming its cause.\n'
    rm -rf "${build_dir}"
    mkdir -p "${build_dir}"
fi

sources_now > "${MANIFEST}"
