#!/usr/bin/env python3
"""Promotes or deletes freshly generated screenshots.

**Why this detour rather than writing the reference directly.** A screenshot
generated by every `make manual` and committed as is would produce a modified
binary on every run, on every machine: the repository's history would fill with
images nobody changed, and a real interface change would drown in them. The
screenshot program therefore never writes the reference — it writes
`<name>.new.png`, and this is where the decision is made.

    the image moved       →  the `.new` REPLACES the reference, git sees a
                             modification, and it means something
    the image did not     →  the `.new` is DELETED, and git sees nothing

The shape is that of a neighbouring project that has held it for a long time;
what changes here is that there is neither Node nor an image library. PNG
decoding is written by hand, because the format Qt writes is the simplest
subset there is — eight bits per channel, no interlacing — and because adding
numpy or Pillow to the toolchain to count differing pixels would be paying a
high price for a subtraction.

**The threshold, and why there are two.** A single threshold on the number of
differing pixels does not tell an entirely redrawn image from an antialiasing
that moved by a hair across all the text. So the *severity* — by how much a
pixel differs — is separated from the *surface* — how many pixels differ that
much. That is what lets encoding noise through without letting a changed line
of text through.

Modes:

    (default)  promotes or deletes
    --check    promotes nothing, deletes everything, and fails if an image moved
    --dry-run  touches nothing, and succeeds whatever happens

`--check` also deletes what it examined, including the images that moved: a
check that left behind the `.new.png` it has just refused would turn every
failure into untracked files to pick up by hand, and `check-untracked.sh` would
see them appear at the next gate.
"""

from __future__ import annotations

import argparse
import pathlib
import struct
import sys
import zlib

# Severity: by how much a channel must differ for the pixel to count. Eight out
# of two hundred and fifty-five, that is three per cent — above what a
# re-encoding moves, far below an intended change of colour.
DEFAULT_PIXEL_THRESHOLD = 8
# Surface: the proportion of pixels differing that much beyond which the image
# has changed.
#
# **One ten-thousandth, and the previous figure was a thousand times too
# generous.** It was one thousandth — a thousand pixels on 1280×800 — on the
# grounds that it was "less than a word". Measured: the mention
# `Encoding: UTF-8, no BOM` added to the window's status bar, twenty-three
# characters, lights up **830**. The threshold thus declared "unchanged" an image
# in which a whole line had changed, and the reference kept by the manual showed
# a window that no longer existed. Issue #313, where the defect showed because it
# fell just under the bar.
#
# A character of this font costs about thirty pixels; a hundred and three pixels
# is three characters. Below that, there is nothing intended left to see.
#
# **It is not this threshold that filters antialiasing**, and that is what allows
# lowering it: the severity takes care of it, and the seventeen other
# screenshots of this repository give 0.000 % from one run to the next. The
# feared noise does not exist on one machine, and between two machines it is
# the named font that prevents it — ADR 0024.
DEFAULT_RATIO_THRESHOLD = 0.0001

GREEN = "\033[32m"
RED = "\033[31m"
BOLD = "\033[1m"
RESET = "\033[0m"

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
# The only two colour types Qt writes for a screenshot: RGB and RGBA.
CHANNELS_OF_COLOUR_TYPE = {2: 3, 6: 4}


class Unreadable(Exception):
    """A PNG this decoder cannot read, said rather than guessed."""


def read_png_size(path: pathlib.Path) -> tuple[int, int]:
    """Width and height, read from the header alone.

    The IHDR is the first chunk and it is twenty-five bytes long: nothing more is
    read, where `read_png` decompresses the whole image.
    """
    with path.open("rb") as handle:
        header = handle.read(len(PNG_SIGNATURE) + 16)
    if not header.startswith(PNG_SIGNATURE):
        raise Unreadable(f"{path}: not a PNG")
    return struct.unpack(">II", header[len(PNG_SIGNATURE) + 8 : len(PNG_SIGNATURE) + 16])


def read_png(path: pathlib.Path) -> tuple[int, int, int, bytes]:
    """Returns (width, height, channels, pixels), the pixels unfiltered.

    Deliberately narrow. A decoder that accepted interlacing and palettes would
    be three times longer and would never have anything to decode: what it reads
    comes from a single writer, `QPixmap::save`.
    """
    data = path.read_bytes()
    if not data.startswith(PNG_SIGNATURE):
        raise Unreadable(f"{path}: not a PNG")

    width = height = channels = 0
    compressed = bytearray()
    offset = len(PNG_SIGNATURE)

    while offset < len(data):
        (length,) = struct.unpack(">I", data[offset : offset + 4])
        kind = data[offset + 4 : offset + 8]
        payload = data[offset + 8 : offset + 8 + length]
        offset += 12 + length  # length, type, data, CRC

        if kind == b"IHDR":
            width, height, depth, colour, compression, filtering, interlace = struct.unpack(
                ">IIBBBBB", payload
            )
            if depth != 8:
                raise Unreadable(f"{path}: {depth} bits per channel, 8 expected")
            if colour not in CHANNELS_OF_COLOUR_TYPE:
                raise Unreadable(f"{path}: colour type {colour}, 2 or 6 expected")
            if compression != 0 or filtering != 0 or interlace != 0:
                raise Unreadable(f"{path}: unexpected compression, filtering or interlacing")
            channels = CHANNELS_OF_COLOUR_TYPE[colour]
        elif kind == b"IDAT":
            compressed += payload
        elif kind == b"IEND":
            break

    if width == 0 or height == 0:
        raise Unreadable(f"{path}: missing header or empty image")

    return width, height, channels, unfilter(zlib.decompress(bytes(compressed)), width, height, channels)


def unfilter(raw: bytes, width: int, height: int, channels: int) -> bytes:
    """Undoes the five PNG filters, line by line.

    Each line is prefixed with the number of its filter, and each filter is
    undone from the pixel on the left, the one above, or both. The previous line
    is already unfiltered when the next one is reached, which is the whole trick
    of the format.
    """
    stride = width * channels
    out = bytearray(stride * height)
    previous = bytearray(stride)

    for row in range(height):
        start = row * (stride + 1)
        kind = raw[start]
        line = bytearray(raw[start + 1 : start + 1 + stride])

        if kind == 0:
            pass  # no prediction: the line already is what it is worth
        elif kind == 1:  # Sub — the pixel on the left
            for i in range(channels, stride):
                line[i] = (line[i] + line[i - channels]) & 0xFF
        elif kind == 2:  # Up — the pixel above
            for i in range(stride):
                line[i] = (line[i] + previous[i]) & 0xFF
        elif kind == 3:  # Average — the mean of the two
            for i in range(stride):
                left = line[i - channels] if i >= channels else 0
                line[i] = (line[i] + ((left + previous[i]) >> 1)) & 0xFF
        elif kind == 4:  # Paeth — whichever of the three predicts best
            for i in range(stride):
                left = line[i - channels] if i >= channels else 0
                upleft = previous[i - channels] if i >= channels else 0
                line[i] = (line[i] + paeth(left, previous[i], upleft)) & 0xFF
        else:
            raise Unreadable(f"unknown line filter {kind}")

        out[row * stride : (row + 1) * stride] = line
        previous = line

    return bytes(out)


def paeth(left: int, up: int, upleft: int) -> int:
    estimate = left + up - upleft
    to_left = abs(estimate - left)
    to_up = abs(estimate - up)
    to_upleft = abs(estimate - upleft)
    if to_left <= to_up and to_left <= to_upleft:
        return left
    if to_up <= to_upleft:
        return up
    return upleft


def difference(new: pathlib.Path, reference: pathlib.Path, severity: int) -> tuple[int, int]:
    """Returns (differing pixels, total pixels), or (-1, 0) if the sizes differ.

    **Two identical files are not decoded.** It is the common case, by far: the
    screenshots are generated under fixed settings, so two runs of the same code
    give the same bytes. Reading fifty kilobytes costs a millisecond, where
    decoding then comparing six images costs a few thousand — and that
    comparison is chained by `make check-local`.
    """
    if new.read_bytes() == reference.read_bytes():
        width, height = read_png_size(new)
        return 0, width * height

    new_width, new_height, new_channels, new_pixels = read_png(new)
    old_width, old_height, old_channels, old_pixels = read_png(reference)

    if (new_width, new_height, new_channels) != (old_width, old_height, old_channels):
        return -1, 0

    total = new_width * new_height

    # Different bytes can carry the same pixels — an encoder that changed
    # version, for instance. The loop is then of no use.
    if new_pixels == old_pixels:
        return 0, total

    differing = 0
    for pixel in range(total):
        base = pixel * new_channels
        for channel in range(new_channels):
            if abs(new_pixels[base + channel] - old_pixels[base + channel]) > severity:
                differing += 1
                break

    return differing, total


def verdict(differing: int, total: int, surface: float) -> str:
    if differing < 0:
        return "changed"
    return "changed" if total > 0 and differing / total > surface else "unchanged"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", required=True, help="the screenshots directory")
    parser.add_argument("--pixel-threshold", type=int, default=DEFAULT_PIXEL_THRESHOLD)
    parser.add_argument("--ratio-threshold", type=float, default=DEFAULT_RATIO_THRESHOLD)
    parser.add_argument(
        "--check", action="store_true", help="fails if an image moved, without promoting anything"
    )
    parser.add_argument("--dry-run", action="store_true", help="touches nothing")
    options = parser.parse_args()

    directory = pathlib.Path(options.dir)
    if not directory.is_dir():
        print(f"{RED}✗ {directory}: missing directory{RESET}", file=sys.stderr)
        return 1

    fresh = sorted(directory.glob("*.new.png"))
    if not fresh:
        print(f"{RED}✗ {directory}: no fresh screenshot to compare{RESET}", file=sys.stderr)
        print("  generate first, with \"make screenshots\"", file=sys.stderr)
        return 1

    writes = not (options.check or options.dry_run)
    changed = []

    for new in fresh:
        reference = new.with_name(new.name.removesuffix(".new.png") + ".png")

        if not reference.exists():
            if writes:
                new.rename(reference)
            changed.append(reference.name)
            print(f"  {GREEN}+{RESET} {reference.name} — new")
            continue

        differing, total = difference(new, reference, options.pixel_threshold)
        said = verdict(differing, total, options.ratio_threshold)

        if said == "changed":
            if writes:
                new.rename(reference)
            changed.append(reference.name)
            share = "dimensions" if differing < 0 else f"{100 * differing / total:.3f} %"
            print(f"  {GREEN}~{RESET} {reference.name} — changed ({share})")
        else:
            if writes:
                new.unlink()
            print(f"  {reference.name} — unchanged ({100 * differing / total:.3f} %)")

    if options.check:
        # Nothing is promoted, and nothing remains: see the header.
        for new in fresh:
            new.unlink(missing_ok=True)

    if options.check and changed:
        print(
            f"{RED}✗ {len(changed)} screenshot(s) no longer match the window "
            f"— run \"make screenshots\"{RESET}",
            file=sys.stderr,
        )
        return 1

    if changed:
        print(f"{GREEN}{len(changed)} screenshot(s) promoted{RESET}")
    else:
        print(f"{GREEN}no screenshot moved{RESET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
